import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineConfig, searchForWorkspaceRoot } from "vite";
import { svelte, vitePreprocess } from "@sveltejs/vite-plugin-svelte";
import license from "rollup-plugin-license";
import { VitePWA } from "vite-plugin-pwa";

/** The libraries bundled into the page and its workers, with their licences (Help → About →
 * Licences). The workers are built first; the page's build writes the list of both. */
type Dep = { name: string | null; version: string | null; license: string | null; licenseText: string | null };
const bundled = new Map<string, Dep>();
const collect = (deps: Dep[]) => deps.forEach((d) => bundled.set(`${d.name}@${d.version}`, d));
const listing = () =>
  "Libraries in ERDTeX (JavaScript)\n\n" +
  "Generated by rollup-plugin-license when the page is built: every library bundled into it.\n" +
  [...bundled.values()]
    .sort((a, b) => (a.name ?? "").localeCompare(b.name ?? ""))
    .map((d) => `\n${"-".repeat(78)}\n${d.name} ${d.version} (${d.license ?? "licence not stated"})\n${"-".repeat(78)}\n\n${(d.licenseText ?? "").trim()}\n`)
    .join("");
const workerLicenses = () => license({ thirdParty: { includePrivate: false, output: collect } });
const pageLicenses = (outDir: string) => license({
  thirdParty: {
    includePrivate: false,
    output: (deps: Dep[]) => {
      collect(deps);
      mkdirSync(fileURLToPath(new URL(outDir, import.meta.url)), { recursive: true });
      writeFileSync(fileURLToPath(new URL(`${outDir}/licenses-javascript.txt`, import.meta.url)), listing());
    },
  },
});

// The page lives in frontend/.  The fonts come from the WebAssembly core (FontFace).
const version = (JSON.parse(readFileSync(new URL("package.json", import.meta.url), "utf8")) as { version: string }).version;

// The desktop app's page (`vite build`, into dist/, for Tauri) or the website (`vite build --mode web`,
// into dist-web/, with relative paths so that it works under any address): they differ in the platform
// module (frontend/src/lib/platform/), see backend.ts.
export default defineConfig(({ mode }) => {
  const web = mode === "web";
  const outDir = web ? "dist-web" : "dist";
  return {
    root: "frontend",
    publicDir: false,
    base: web ? "./" : "/",
    define: { __APP_VERSION__: JSON.stringify(version) },
    resolve: { alias: { "#platform": fileURLToPath(new URL(`frontend/src/lib/platform/${web ? "web" : "desktop"}.ts`, import.meta.url)) } },
    plugins: [
      svelte({ configFile: false, preprocess: vitePreprocess() }),
      pageLicenses(outDir),
      // the website: kept in the browser after the first visit (works offline; a new version asks to
      // reload). Not pdf.js (the LaTeX preview, which a browser can't have); the manuals when saved.
      ...(web
        ? [
            VitePWA({
              registerType: "prompt",
              injectRegister: false,
              manifest: false,
              workbox: {
                globPatterns: ["**/*.{js,mjs,css,html,wasm,txt}"],
                globIgnores: ["**/pdf-*.js", "**/pdf.worker*"],
                maximumFileSizeToCacheInBytes: 8 * 1024 * 1024,
                runtimeCaching: [{ urlPattern: /\.pdf$/, handler: "CacheFirst", options: { cacheName: "manuals" } }],
              },
            }),
          ]
        : []),
    ],
    worker: { plugins: () => [workerLicenses()] },
    clearScreen: false,
    build: { outDir: `../${outDir}`, emptyOutDir: true, target: "es2022" },
    server: {
      port: 1420,
      strictPort: true,
      host: "127.0.0.1",
      watch: { ignored: ["**/src-tauri/**", "**/target/**"] },
      // the LaTeX packages and their manuals (latex_packages/, beside this folder) and the licences
      // (LICENSE, beside this folder) are built in
      fs: { allow: [searchForWorkspaceRoot(process.cwd()), fileURLToPath(new URL("../latex_packages", import.meta.url)), fileURLToPath(new URL("../LICENSE", import.meta.url))] },
    },
  };
});
